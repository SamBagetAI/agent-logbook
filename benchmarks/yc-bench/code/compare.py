"""YC-Bench, Claude Haiku 5.5, seeds 1-5: its own scratchpad only, against scratchpad + Register.
With the published Claude 5.5 runs of seeds 1-3 for reference.

  YC_BENCH_REPO=/path/to/yc-bench python compare.py    # reads ../data/runs.zip; writes ../results/runs.csv and summary.txt

Without YC_BENCH_REPO, the published runs are left out.
"""
import csv
import json
import math
import os
import statistics as st
import zipfile
from pathlib import Path

from traps import summary

HERE = Path(__file__).resolve().parent
DATA, RESULTS = HERE.parent / "data", HERE.parent / "results"
SEEDS = range(1, 6)
LABEL = {"base": "Haiku 5.5, scratchpad", "reg": "Haiku 5.5, scratchpad + Register",
         "claude-sonnet-5.5": "Sonnet 5.5, scratchpad (published)", "claude-opus-5.5": "Opus 5.5, scratchpad (published)"}

z = zipfile.ZipFile(DATA / "runs.zip")
runs = {}
for name in z.namelist():
    folder, _, file = name.partition("/")[2].partition("/")
    if file.startswith("yc_bench_result_") and file.endswith(".json"):
        arm, seed = folder.rsplit("_s", 1)
        runs[(arm, int(seed))] = summary(json.loads(z.read(name)))
repo = os.environ.get("YC_BENCH_REPO")
if repo:
    for model in ("claude-sonnet-5.5", "claude-opus-5.5"):
        for seed in range(1, 4):
            p = Path(repo) / "results" / f"yc_bench_result_default_{seed}_openrouter_anthropic_{model}.json"
            runs[(model, seed)] = summary(json.loads(p.read_text()))

RESULTS.mkdir(exist_ok=True)
order = sorted(runs, key=lambda k: (k[1], list(LABEL).index(k[0]) if k[0] in LABEL else 9, k[0]))
with open(RESULTS / "runs.csv", "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=["setup"] + list(next(iter(runs.values()))))
    w.writeheader()
    for k in order:
        w.writerow({"setup": k[0], **runs[k]})

out = ["YC-Bench (default config), final funds and contracts from the trap clients. Generated by code/compare.py.",
       "Setups: base = the benchmark as published (the agent's own scratchpad); reg = the same plus the Register;",
       "base_s100 and trial_s101 are outside the evaluation (a check run and the trial before the rewrite).", "",
       "| Seed | Setup | Final funds | Cost | Turns | End | Trap contracts | of which failed / cancelled | taken after a failure |",
       "|---|---|---|---|---|---|---|---|---|"]
for k in order:
    r = runs[k]
    out.append(f"| {k[1]} | {k[0]} | ${r['final_funds_usd']:,.0f} | ${r['cost_usd']:.2f} | {r['turns']} | {'80-turn trial' if k[0] == 'trial' else r['end']} | "
               f"{r['trap_contracts']} | {r['trap_failed']} / {r['trap_cancelled']} | {r['trap_after_a_failure']} |")
d = [runs[("reg", s)]["final_funds_usd"] - runs[("base", s)]["final_funds_usd"] for s in SEEDS]
mean, sd = st.mean(d), st.stdev(d)
out += ["", f"Paired over seeds 1-5, Register minus scratchpad: {mean:+,.0f} on average ({', '.join(f'{x:+,.0f}' for x in d)}); "
        f"paired t = {mean / (sd / math.sqrt(len(d))):.2f}; Register ahead on {sum(x > 0 for x in d)}/{len(d)}"
        + (f", one-sided sign test p = {0.5 ** len(d):.3f}" if all(x > 0 for x in d) else "") + "."]
for arm in ("base", "reg"):
    rs = [runs[(arm, s)] for s in SEEDS]
    out.append(f"{LABEL[arm]}: mean funds ${st.mean(r['final_funds_usd'] for r in rs):,.0f}, mean cost ${st.mean(r['cost_usd'] for r in rs):.2f}, "
               f"trap contracts per run {st.mean(r['trap_contracts'] for r in rs):.1f}, taken after a failure {st.mean(r['trap_after_a_failure'] for r in rs):.1f}")
if repo:
    reg13 = st.mean(runs[("reg", s)]["final_funds_usd"] for s in range(1, 4))
    out.append(f"Seeds 1-3: Haiku 5.5 + Register ${reg13:,.0f} at ${st.mean(runs[('reg', s)]['cost_usd'] for s in range(1, 4)):.2f} per run.")
    for model in ("claude-sonnet-5.5", "claude-opus-5.5"):
        rs = [runs[(model, s)] for s in range(1, 4)]
        out.append(f"Seeds 1-3: {LABEL[model]} ${st.mean(r['final_funds_usd'] for r in rs):,.0f} at ${st.mean(r['cost_usd'] for r in rs):.2f} per run, "
                   f"trap contracts per run {st.mean(r['trap_contracts'] for r in rs):.1f}")
out.append(f"Trap clients: {runs[('base', 1)]['trap_clients']} (the same in every run above).")
text = "\n".join(out)
(RESULTS / "summary.txt").write_text(text + "\n")
print(text)
